const dictionaries: Record<Lang, Dict> = { en, hi, mr }
const STORAGE_KEY = "packsmart.lang"

interface I18nValue {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: DictKey) => string
}

const I18nContext = createContext<I18nValue>({ lang: "en", setLang: () => {}, t: (k) => en[k] })

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en")

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY)
      if (saved === "hi" || saved === "mr" || saved === "en") {
        // eslint-disable-next-line react-hooks/set-state-in-effect -- restoring a saved preference after hydration
        setLangState(saved)
      }
    } catch {
      /* storage unavailable */
    }
  }, [])

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem(STORAGE_KEY, l)
    } catch {
      /* storage unavailable */
    }
  }, [])

  const value = useMemo<I18nValue>(() => ({ lang, setLang, t: (k) => dictionaries[lang][k] ?? en[k] }), [lang, setLang])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)

